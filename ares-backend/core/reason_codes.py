"""Reason-Code-Katalog und fachliche Fehler (K-2, A2 M5/M17).

``ReasonCode`` ist das zentrale Register aller Reason-Codes, die das Backend
heute als String erzeugt (API-Fehlerdetails, Status-Bloecke fuer API/PDF,
Audit-/Ereignis-Eintraege). Die Werte sind 1:1 die bestehenden Literale --
inklusive der historisch gemischten Schreibweise (``COST_EVIDENCE_INVALID``
neben ``concurrent_decision``). Eine Vereinheitlichung (Namespaces, Aliase,
RFC-9457-Envelope) ist bewusst NICHT Teil dieses Schritts (siehe U-2), weil
Monolith, Reporting und PDF die Werte heute woertlich auswerten.

Der Vertragstest ``tests/test_reason_code_catalog_contract.py`` haelt den
Katalog in beide Richtungen deckungsgleich mit dem Code: jeder statisch
erzeugte oder ausgewertete Code steht hier, und hier steht kein Code, den
niemand erzeugt.

``DomainError`` ist die fachliche Exception mit Reason-Code. Services werfen
sie statt ``fastapi.HTTPException``; ``core/error_handlers.py`` bildet sie
zentral auf exakt die HTTP-Antwort ab, die heute ``HTTPException(status_code=
http_status, detail=as_detail())`` erzeugt (Status, Body, Header byte-gleich).
Dieses Modul importiert bewusst nichts aus FastAPI.
"""
